const builtins: Record<string, Dictionary> = { sv, en, es };

export function builtinDictionary(locale: string): Dictionary | undefined {
  if (builtins[locale]) return builtins[locale];
  const base = locale.split("-")[0] ?? locale;
  if (base === "nb" || base === "nn" || base === "no") return undefined;
  return builtins[base];
}

export { builtins };
