function place(input: {
  id: string;
  category: PlaceCategory;
  name: string;
  description: LocalizedText;
  imageUrl: string;
  lat: number;
  lng: number;
  address?: string;
  hours?: string;
  phone?: string;
  whatsapp?: string;
  website?: string;
  bookingUrl?: string;
  discountCode?: string;
  discountLabel?: LocalizedText;
  sponsored?: boolean;
  monetization?: Place["monetization"];
}): Place {
  return {
    ...stamp(90),
    organizationId: ORG_ID,
    sponsored: false,
    monetization: { kind: "none" },
    ...input,
  };
}

